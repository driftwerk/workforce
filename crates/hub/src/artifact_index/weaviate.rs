    /// A Weaviate that holds what it is given, answering as 1.28.4 and
    /// 1.36.8 do: a replacement of an object it lacks 500 `no object with
    /// id`, a creation of one it holds 422 `already exists`, and, while
    /// its shard is read-only, every write and removal 500 with nothing
    /// changed.
    #[derive(Default)]
    struct Holding {
        /// Object id to `(artifactId, text)`.
        held: Mutex<std::collections::BTreeMap<String, (String, String)>>,
        read_only: std::sync::atomic::AtomicBool,
        /// Removals asked for, and times it was asked to search.
        removals: std::sync::atomic::AtomicUsize,
        searches: std::sync::atomic::AtomicUsize,
        /// The class's description; `None` while there is no class.
        class: Mutex<Option<String>>,
        /// Whether an object sent to a class that is not there makes one,
        /// as Weaviate does by default; otherwise it is answered 422.
        autoschema: std::sync::atomic::AtomicBool,
        /// The class is dropped right after the next time it is read: as
        /// between a writer's look at it and its write.
        drop_after_read: std::sync::atomic::AtomicBool,
        /// Classes made, and GraphQL requests answered.
        classes_made: std::sync::atomic::AtomicUsize,
        queries: std::sync::atomic::AtomicUsize,
        /// A replacement of an object it lacks is answered 404, and not
        /// 500 "no object with id" as 1.28.4 and 1.36.8 answer.
        missing_is_404: std::sync::atomic::AtomicBool,
        /// A replacement is answered 500 for this reason, whatever it is of.
        put_fails: Mutex<Option<String>>,
        /// The next creation finds the object made by another writer with
        /// this text, just before it.
        made_meanwhile: Mutex<Option<String>>,
        /// Creations asked for.
        creations: std::sync::atomic::AtomicUsize,
        /// The class is dropped right after the next replacement is taken.
        drop_after_put: std::sync::atomic::AtomicBool,
        /// The class is not shown: its read is answered 503.
        schema_fails: std::sync::atomic::AtomicBool,
    }

    /// What Weaviate 1.28.4 wrote as the description of a class it made
    /// for itself.
    const AUTO_DESCRIPTION: &str =
        "This property was generated by Weaviate's auto-schema feature on Sat Oct 10 03:45:10 2026";

    impl Holding {
        /// Holding the hub's class, empty.
        fn ours() -> Arc<Self> {
            let fake = Self::default();
            *fake.class.lock().unwrap() = Some(HUB_DESCRIPTION.to_string());
            Arc::new(fake)
        }

        /// The class dropped, with everything in it.
        fn drop_class(&self) {
            *self.class.lock().unwrap() = None;
            self.held.lock().unwrap().clear();
        }

        fn class_described(&self) -> Option<String> {
            self.class.lock().unwrap().clone()
        }

        fn artifacts(&self) -> Vec<String> {
            let held = self.held.lock().unwrap();
            let mut ids: Vec<String> = held.values().map(|(id, _)| id.clone()).collect();
            ids.sort();
            ids
        }

        fn text(&self, artifact: &str) -> Option<String> {
            let held = self.held.lock().unwrap();
            let of = held.values().find(|(id, _)| id == artifact);
            of.map(|(_, text)| text.clone())
        }

        /// Serve on a port of its own; the URL.
        async fn serving(self: &Arc<Self>) -> String {
            use axum::extract::{Path, State};
            use axum::http::StatusCode;
            use axum::response::IntoResponse;
            use axum::routing::{get, post, put};
            use std::sync::atomic::Ordering;
            type Fake = State<Arc<Holding>>;
            fn refusal(status: StatusCode, message: &str) -> axum::response::Response {
                let said = serde_json::json!({ "error": [{ "message": message }] });
                (status, axum::Json(said)).into_response()
            }
            fn read_only(fake: &Holding) -> Option<axum::response::Response> {
                let said = "put object: import into index artifacts: put local object: \
                    shard=\"hc5MkRfztNlu\": store is read-only due to: manually set by user";
                fake.read_only
                    .load(Ordering::SeqCst)
                    .then(|| refusal(StatusCode::INTERNAL_SERVER_ERROR, said))
            }
            fn of(object: &serde_json::Value) -> (String, String) {
                let said = |key: &str| object["properties"][key].as_str().unwrap().to_string();
                (said("artifactId"), said("text"))
            }
            let replaced =
                |State(fake): Fake,
                 Path((_, id)): Path<(String, String)>,
                 axum::Json(object): axum::Json<serde_json::Value>| async move {
                    if let Some(refused) = read_only(&fake) {
                        return refused;
                    }
                    if let Some(why) = fake.put_fails.lock().unwrap().clone() {
                        return refusal(StatusCode::INTERNAL_SERVER_ERROR, &why);
                    }
                    let mut held = fake.held.lock().unwrap();
                    match held.get_mut(&id) {
                        Some(there) => {
                            *there = of(&object);
                            if fake.drop_after_put.swap(false, Ordering::SeqCst) {
                                *fake.class.lock().unwrap() = None;
                            }
                            StatusCode::OK.into_response()
                        }
                        None if fake.missing_is_404.load(Ordering::SeqCst) => {
                            StatusCode::NOT_FOUND.into_response()
                        }
                        None => refusal(
                            StatusCode::INTERNAL_SERVER_ERROR,
                            &format!("no object with id '{id}'"),
                        ),
                    }
                };
            let created = |State(fake): Fake, axum::Json(object): axum::Json<serde_json::Value>| async move {
                if let Some(refused) = read_only(&fake) {
                    return refused;
                }
                {
                    let mut class = fake.class.lock().unwrap();
                    if class.is_none() {
                        if !fake.autoschema.load(Ordering::SeqCst) {
                            // As 1.28.4 and 1.36.8 answer with auto-schema off.
                            let gone = "invalid object: class \"Artifacts\" not found in schema";
                            return refusal(StatusCode::UNPROCESSABLE_ENTITY, gone);
                        }
                        *class = Some(AUTO_DESCRIPTION.to_string());
                    }
                }
                fake.creations.fetch_add(1, Ordering::SeqCst);
                let id = object["id"].as_str().unwrap().to_string();
                let mut held = fake.held.lock().unwrap();
                if let Some(theirs) = fake.made_meanwhile.lock().unwrap().take() {
                    let artifact = object["properties"]["artifactId"].as_str().unwrap();
                    held.insert(id.clone(), (artifact.to_string(), theirs));
                }
                if held.contains_key(&id) {
                    let said = format!("id '{id}' already exists");
                    return refusal(StatusCode::UNPROCESSABLE_ENTITY, &said);
                }
                held.insert(id, of(&object));
                StatusCode::OK.into_response()
            };
            let removed = |State(fake): Fake, Path((_, id)): Path<(String, String)>| async move {
                fake.removals.fetch_add(1, Ordering::SeqCst);
                if let Some(refused) = read_only(&fake) {
                    return refused;
                }
                match fake.held.lock().unwrap().remove(&id) {
                    Some(_) => StatusCode::NO_CONTENT.into_response(),
                    None => StatusCode::NOT_FOUND.into_response(),
                }
            };
            let looked_for = |State(fake): Fake, Path((_, id)): Path<(String, String)>| async move {
                match fake.held.lock().unwrap().contains_key(&id) {
                    true => StatusCode::OK,
                    false => StatusCode::NOT_FOUND,
                }
            };
            let listed = |State(fake): Fake| async move {
                let held = fake.held.lock().unwrap();
                let objects: Vec<serde_json::Value> = held
                    .iter()
                    .map(|(id, (artifact, _))| match artifact.is_empty() {
                        true => serde_json::json!({ "id": id, "properties": {} }),
                        false => serde_json::json!({ "id": id, "properties": { "artifactId": artifact } }),
                    })
                    .collect();
                axum::Json(serde_json::json!({ "objects": objects }))
            };
            let asked = |State(fake): Fake, axum::Json(asked): axum::Json<serde_json::Value>| async move {
                fake.queries.fetch_add(1, Ordering::SeqCst);
                let held = fake.held.lock().unwrap();
                let query = asked["query"].as_str().unwrap();
                let mut data = serde_json::Map::new();
                if query.contains("Get") {
                    fake.searches.fetch_add(1, Ordering::SeqCst);
                    let limit = query
                        .split("limit: ")
                        .nth(1)
                        .and_then(|rest| rest.split(|c: char| !c.is_ascii_digit()).next())
                        .and_then(|n| n.parse::<usize>().ok())
                        .unwrap_or(usize::MAX);
                    let found: Vec<serde_json::Value> = held
                        .values()
                        .take(limit)
                        .map(|(id, _)| serde_json::json!({ "artifactId": id, "_additional": { "certainty": 0.9 } }))
                        .collect();
                    data.insert("Get".into(), serde_json::json!({ "Artifacts": found }));
                }
                if query.contains("Aggregate") {
                    let count =
                        serde_json::json!({ "Artifacts": [{ "meta": { "count": held.len() } }] });
                    data.insert("Aggregate".into(), count);
                }
                axum::Json(serde_json::json!({ "data": data }))
            };
            let class = |State(fake): Fake| async move {
                if fake.schema_fails.load(Ordering::SeqCst) {
                    return StatusCode::SERVICE_UNAVAILABLE.into_response();
                }
                let described = fake.class_described();
                if fake.drop_after_read.swap(false, Ordering::SeqCst) {
                    fake.drop_class();
                }
                match described {
                    Some(described) => axum::Json(serde_json::json!({
                        "class": "Artifacts",
                        "description": described,
                    }))
                    .into_response(),
                    None => StatusCode::NOT_FOUND.into_response(),
                }
            };
            let make = |State(fake): Fake, axum::Json(asked): axum::Json<serde_json::Value>| async move {
                let mut class = fake.class.lock().unwrap();
                if class.is_some() {
                    let said = "class name \"Artifacts\" already exists";
                    return refusal(StatusCode::UNPROCESSABLE_ENTITY, said);
                }
                fake.classes_made.fetch_add(1, Ordering::SeqCst);
                *class = Some(
                    asked["description"]
                        .as_str()
                        .unwrap_or_default()
                        .to_string(),
                );
                StatusCode::OK.into_response()
            };
            let app = axum::Router::new()
                .route("/v1/schema/Artifacts", get(class))
                .route("/v1/schema", post(make))
                .route("/v1/objects", post(created).get(listed))
                .route(
                    "/v1/objects/{class}/{id}",
                    put(replaced).delete(removed).get(looked_for),
                )
                .route("/v1/graphql", post(asked))
                .with_state(Arc::clone(self));
            let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
            let url = format!("http://{}", listener.local_addr().unwrap());
            tokio::spawn(async move { axum::serve(listener, app).await.unwrap() });
            url
        }
    }

