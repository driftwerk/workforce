    /// No request to Weaviate waits for ever (DW-620 invariant 8): one
    /// that accepts a request and never answers it fails every call within
    /// the client's request timeout. The client had none, and such a
    /// Weaviate stalled whoever asked, the index keeper among them.
    #[tokio::test]
    async fn a_weaviate_that_never_answers_keeps_no_call_waiting() {
        use std::time::Duration;
        let app = with_class(axum::Router::new()).fallback(|| async {
            std::future::pending::<()>().await;
            axum::http::StatusCode::OK
        });
        let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let url = format!("http://{}", listener.local_addr().unwrap());
        tokio::spawn(async move { axum::serve(listener, app).await.unwrap() });
        let request = Duration::from_millis(300);
        let weaviate = WeaviateArtifacts::waiting(&url, None, Duration::from_secs(5), request);
        let page = [("a".to_string(), "h".to_string())];
        let within = |what: &'static str, began: std::time::Instant| {
            let took = began.elapsed();
            assert!(took < request * 6, "{what} was kept waiting {took:?}");
        };
        // Each bounded here too, so that a client with no timeout fails
        // this test and does not hang it.
        let limit = Duration::from_secs(10);
        macro_rules! fails_in_time {
            ($what:literal, $call:expr) => {{
                let began = std::time::Instant::now();
                let ended = tokio::time::timeout(limit, $call).await;
                assert!(ended.expect(concat!($what, " never ended")).is_err(), $what);
                within($what, began);
            }};
        }
        fails_in_time!("a write", weaviate.upsert("a", "some text", "h"));
        fails_in_time!("a removal", weaviate.remove("a"));
        fails_in_time!("a search", weaviate.search("anything", 3));
        fails_in_time!("a count", weaviate.count());
        fails_in_time!("a look for what is held", weaviate.differing(&page));
        fails_in_time!("a listing", weaviate.ids_after(None, 10));
        // What a hub is given unless told otherwise.
        assert_eq!(REQUEST_TIMEOUT, Duration::from_secs(30));
        assert_eq!(CONNECT_TIMEOUT, Duration::from_secs(5));
    }

