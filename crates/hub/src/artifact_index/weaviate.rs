    /// An artifact indexed again is replaced where it is, and never
    /// removed first: a write Weaviate does not take leaves what it held,
    /// as it was. One it does not hold is created; one created by another
    /// hub meanwhile is replaced after all.
    #[tokio::test]
    async fn a_write_weaviate_does_not_take_leaves_what_it_held() {
        use std::sync::atomic::Ordering;
        let fake = Holding::ours();
        let weaviate = WeaviateArtifacts::new(&fake.serving().await, None);
        weaviate.upsert("a", "first text", "h1").await.unwrap();
        weaviate.upsert("a", "second text", "h2").await.unwrap();
        assert_eq!(fake.artifacts(), ["a"]);
        assert_eq!(fake.text("a").as_deref(), Some("second text"));

        fake.read_only.store(true, Ordering::SeqCst);
        let told = weaviate.upsert("a", "third text", "h3").await.unwrap_err();
        assert!(
            format!("{told:#}").contains("store is read-only"),
            "{told:#}"
        );
        assert!(weaviate.upsert("b", "another", "h").await.is_err());
        assert_eq!(fake.text("a").as_deref(), Some("second text"), "as it was");
        assert_eq!(fake.artifacts(), ["a"]);
        assert_eq!(
            fake.removals.load(Ordering::SeqCst),
            0,
            "nothing is removed to be written"
        );

        fake.read_only.store(false, Ordering::SeqCst);
        weaviate.upsert("a", "third text", "h3").await.unwrap();
        weaviate.upsert("b", "another", "h").await.unwrap();
        assert_eq!(fake.artifacts(), ["a", "b"]);
        assert_eq!(fake.text("a").as_deref(), Some("third text"));
        weaviate.remove("b").await.unwrap();
        assert_eq!(fake.artifacts(), ["a"]);
    }

    /// Through a write outage of many rounds, with artifacts waiting to be
    /// indexed and the keeper asking each round whether Weaviate takes a
    /// write, by having it take again one it holds: every artifact it
    /// held it holds still, as it was; the pending list is what was
    /// written meanwhile and does not grow; nothing is counted against
    /// anything. When the writes come back the rest is indexed.
    #[tokio::test(flavor = "multi_thread")]
    async fn a_write_outage_costs_weaviate_nothing_it_held() {
        use super::super::ArtifactIndex;
        use std::sync::atomic::Ordering;
        use std::time::Duration;
        use workforce_orchestrator::artifact_store::{
            Artifact, ArtifactBackend, ArtifactType, IndexPace, KnowledgeStore, Visibility,
        };
        let fake = Holding::ours();
        let url = fake.serving().await;
        workforce_postgres::test_support::with_test_pool(
            KnowledgeStore::build_pool,
            |pool| async move {
                let index = ArtifactIndex::new(WeaviateArtifacts::new(&url, None));
                let store = KnowledgeStore::new(pool.clone(), Some(Arc::new(index)));
                let store = store.await.unwrap();
                let write = |id: &'static str| {
                    let store = Arc::clone(&store);
                    async move {
                        let text = format!("what {id} says");
                        let note = Artifact::new(
                            id,
                            ArtifactType::Spec,
                            id,
                            &text,
                            "owner",
                            "owner",
                            Visibility::Public,
                            Vec::new(),
                        );
                        store.create(&note).await.unwrap();
                    }
                };
                let pending = || async {
                    let conn = pool.get().await.unwrap();
                    let noted = "SELECT artifact_id, tries FROM artifact_index_pending ORDER BY 1";
                    let rows = conn.query(noted, &[]).await.unwrap();
                    rows.iter()
                        .map(|row| (row.get::<_, String>(0), row.get::<_, i32>(1)))
                        .collect::<Vec<_>>()
                };
                let until = |what: &'static str, met: Box<dyn Fn() -> bool + Send>| async move {
                    let begun = std::time::Instant::now();
                    while !met() {
                        assert!(
                            begun.elapsed() < Duration::from_secs(60),
                            "not in time: {what}"
                        );
                        tokio::time::sleep(Duration::from_millis(20)).await;
                    }
                };
                let pace = IndexPace {
                    retry: Duration::from_millis(20),
                    watch: Duration::from_millis(150),
                    reconcile: Duration::from_secs(3600),
                    backoff: Duration::ZERO,
                    ..IndexPace::DEFAULT
                };
                store.keep_index_complete(pace);
                for id in ["one", "two", "three"] {
                    write(id).await;
                }
                let held = Arc::clone(&fake);
                until("three held", Box::new(move || held.artifacts().len() == 3)).await;
                // And none of them pending: a second write of one, by the
                // keeper beside the write's own try, may be under way yet,
                // and would be noted again for failing once writes fail.
                let begun = std::time::Instant::now();
                while !pending().await.is_empty() {
                    assert!(begun.elapsed() < Duration::from_secs(60), "none pending");
                    tokio::time::sleep(Duration::from_millis(20)).await;
                }
                let texts = |fake: &Holding| {
                    let of = |id: &str| fake.text(id).unwrap();
                    [of("one"), of("three"), of("two")]
                };
                let before = texts(&fake);

                fake.read_only.store(true, Ordering::SeqCst);
                write("four").await;
                write("five").await;
                // Each round gives Weaviate the two again.
                let begun = std::time::Instant::now();
                while !pending().await.iter().all(|(_, tries)| *tries >= 15) {
                    assert!(begun.elapsed() < Duration::from_secs(60), "fifteen rounds");
                    tokio::time::sleep(Duration::from_millis(20)).await;
                }
                assert_eq!(fake.artifacts(), ["one", "three", "two"], "all it held");
                assert_eq!(texts(&fake), before, "as they were");
                assert_eq!(fake.removals.load(Ordering::SeqCst), 0);
                let left = pending().await;
                let waiting: Vec<&str> = left.iter().map(|(id, _)| id.as_str()).collect();
                assert_eq!(waiting, ["five", "four"], "what was written, and no more");
                let state = store.index_state();
                assert_eq!(state.failing.len(), 2, "tried for as long as it lasts");
                assert!(state.last_error.unwrap().contains("store is read-only"));

                fake.read_only.store(false, Ordering::SeqCst);
                let held = Arc::clone(&fake);
                until(
                    "the rest indexed",
                    Box::new(move || held.artifacts().len() == 5),
                )
                .await;
                let begun = std::time::Instant::now();
                while !pending().await.is_empty() {
                    assert!(begun.elapsed() < Duration::from_secs(60));
                    tokio::time::sleep(Duration::from_millis(20)).await;
                }
                assert_eq!(texts(&fake), before);
            },
        )
        .await;
    }

    #[tokio::test]
    async fn artifacts_are_counted_and_missed_without_listing_the_class() {
        use axum::routing::{get, post};
        let app = axum::Router::new()
            .route(
                "/v1/graphql",
                post(|axum::Json(asked): axum::Json<serde_json::Value>| async move {
                    assert!(asked["query"].as_str().unwrap().contains("Aggregate"));
                    axum::Json(serde_json::json!({
                        "data": { "Aggregate": { "Artifacts": [{ "meta": { "count": 7 } }] } }
                    }))
                }),
            )
            .route(
                "/v1/objects/{class}/{id}",
                get(|axum::extract::Path((_, id)): axum::extract::Path<(String, String)>| async move {
                    if id == object_id("held").to_string() {
                        axum::http::StatusCode::NO_CONTENT
                    } else {
                        axum::http::StatusCode::NOT_FOUND
                    }
                }),
            )
            .route(
                "/v1/objects",
                get(|| async { panic!("the class is not listed") as axum::http::StatusCode }),
            );
        let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let url = format!("http://{}", listener.local_addr().unwrap());
        tokio::spawn(async move { axum::serve(listener, app).await.unwrap() });
        let weaviate = WeaviateArtifacts::new(&url, None);
        assert_eq!(weaviate.count().await.unwrap(), 7);
        let page = [
            ("held".to_string(), "any".to_string()),
            ("lacked".to_string(), "any".to_string()),
        ];
        assert_eq!(weaviate.differing(&page).await.unwrap(), ["lacked"]);
    }
