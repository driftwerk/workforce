//! Skill config loader — loads per-skill `config.toml` with vault and env
//! var expansion via [`workforce_common::config_expand`].
//!
//! Each skill can have its own `config.toml` alongside its `SKILL.md`.
//! Values containing `${VAR}` or `${VAR:-default}` are expanded from the
//! process environment; values containing `${vault:path}` are resolved from
//! the secrets vault. Vault references are expanded first so a vault value
//! can itself contain `${VAR}` placeholders if needed.

use std::path::Path;

use workforce_common::config_expand::{expand_env_vars_in_table, expand_vault_refs_in_table};
use workforce_common::settings::VaultResolver;

/// Result of loading a skill's config.
#[derive(Debug, Clone)]
pub struct SkillConfig {
    /// The raw TOML table (after expansion).
    pub table: toml::Table,
    /// Where the config was loaded from.
    pub source: SkillConfigSource,
}

/// Where the config was loaded from.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SkillConfigSource {
    /// Loaded from the skill's own `config.toml`.
    SkillDir,
    /// Loaded from a legacy section in `workforce.toml`.
    WorkforceToml,
}

/// Config status for display in skill listings.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ConfigStatus {
    /// Has a `config.toml` in the skill directory.
    Configured,
    /// Using legacy config from `workforce.toml`.
    LegacyConfigured,
    /// No config found.
    Unconfigured,
}

/// Load a skill's `config.toml` from its directory (env var expansion only).
///
/// Returns `Ok(None)` if no `config.toml` exists (which is fine — skill may not need config).
pub fn load_skill_config(skill_dir: &Path) -> eyre::Result<Option<SkillConfig>> {
    load_skill_config_with_vault(skill_dir, None)
}

/// Load a skill's `config.toml` with both env var and vault reference expansion.
///
/// Vault references (`${vault:path}`) are resolved first, then env vars (`${VAR}`).
/// If `vault` is `None`, vault references are left as empty strings.
pub fn load_skill_config_with_vault(
    skill_dir: &Path,
    vault: Option<&dyn VaultResolver>,
) -> eyre::Result<Option<SkillConfig>> {
    let config_path = skill_dir.join("config.toml");
    if !config_path.is_file() {
        return Ok(None);
    }

    let content = std::fs::read_to_string(&config_path)
        .map_err(|e| eyre::eyre!("Failed to read {}: {}", config_path.display(), e))?;

    let mut table: toml::Table = content
        .parse()
        .map_err(|e| eyre::eyre!("Failed to parse {}: {}", config_path.display(), e))?;

    if let Some(v) = vault {
        expand_vault_refs_in_table(&mut table, v);
    }
    expand_env_vars_in_table(&mut table);

    Ok(Some(SkillConfig {
        table,
        source: SkillConfigSource::SkillDir,
    }))
}

/// Deserialize a [`SkillConfig`] into a typed struct.
pub fn deserialize_skill_config<T: serde::de::DeserializeOwned>(
    config: &SkillConfig,
) -> eyre::Result<T> {
    let value = toml::Value::Table(config.table.clone());
    value
        .try_into()
        .map_err(|e| eyre::eyre!("Failed to deserialize skill config: {}", e))
}

/// Generate a default `config.toml` template for a skill.
///
/// Built-in skills provide their own templates via `default_toml()` methods.
/// For SKILL.md-based skills, generates a template from required config keys.
pub fn generate_default_config(skill_name: &str, required_config_keys: &[String]) -> String {
    let mut lines = vec![
        format!("# Configuration for {}", skill_name),
        format!("# Generated by: workforce skill init {}", skill_name),
        String::new(),
    ];

    if required_config_keys.is_empty() {
        lines.push("# This skill has no required configuration.".to_string());
        lines.push("# Add custom key = \"value\" pairs as needed.".to_string());
    } else {
        for key in required_config_keys {
            lines.push(format!("# {} = \"\"  # Required", key));
        }
    }

    lines.join("\n") + "\n"
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn load_skill_config_from_dir() {
        let tmp = tempfile::tempdir().unwrap();
        let config_content = r#"
            name = "test"
            value = "hello"
        "#;
        std::fs::write(tmp.path().join("config.toml"), config_content).unwrap();

        let result = load_skill_config(tmp.path()).unwrap();
        assert!(result.is_some());
        let config = result.unwrap();
        assert_eq!(config.source, SkillConfigSource::SkillDir);
        assert_eq!(config.table["name"].as_str().unwrap(), "test");
    }

    #[test]
    fn load_skill_config_no_file() {
        let tmp = tempfile::tempdir().unwrap();
        let result = load_skill_config(tmp.path()).unwrap();
        assert!(result.is_none());
    }

    #[test]
    fn load_skill_config_with_env_expansion() {
        std::env::set_var("TEST_SKILL_CFG_TOKEN", "secret-123");
        let tmp = tempfile::tempdir().unwrap();
        let config_content = r#"token = "${TEST_SKILL_CFG_TOKEN}""#;
        std::fs::write(tmp.path().join("config.toml"), config_content).unwrap();

        let config = load_skill_config(tmp.path()).unwrap().unwrap();
        assert_eq!(config.table["token"].as_str().unwrap(), "secret-123");

        std::env::remove_var("TEST_SKILL_CFG_TOKEN");
    }

    #[test]
    fn deserialize_into_typed_struct() {
        #[derive(serde::Deserialize)]
        struct TestConfig {
            name: String,
            count: i64,
        }

        let tmp = tempfile::tempdir().unwrap();
        let config_content = r#"
            name = "test-skill"
            count = 42
        "#;
        std::fs::write(tmp.path().join("config.toml"), config_content).unwrap();

        let config = load_skill_config(tmp.path()).unwrap().unwrap();
        let typed: TestConfig = deserialize_skill_config(&config).unwrap();
        assert_eq!(typed.name, "test-skill");
        assert_eq!(typed.count, 42);
    }

    #[test]
    fn generate_default_no_requirements() {
        let output = generate_default_config("my-skill", &[]);
        assert!(output.contains("my-skill"));
        assert!(output.contains("no required configuration"));
    }

    #[test]
    fn generate_default_with_requirements() {
        let keys = vec!["api_key".to_string(), "base_url".to_string()];
        let output = generate_default_config("my-skill", &keys);
        assert!(output.contains("api_key"));
        assert!(output.contains("base_url"));
        assert!(output.contains("Required"));
    }

    struct MockVault {
        secrets: std::collections::HashMap<String, String>,
    }

    impl MockVault {
        fn new(entries: &[(&str, &str)]) -> Self {
            Self {
                secrets: entries
                    .iter()
                    .map(|(k, v)| (k.to_string(), v.to_string()))
                    .collect(),
            }
        }
    }

    impl VaultResolver for MockVault {
        fn resolve(&self, path: &str) -> Option<String> {
            self.secrets.get(path).cloned()
        }
    }

    #[test]
    fn load_skill_config_with_vault_expansion() {
        let vault = MockVault::new(&[("slack.token", concat!("xoxb-f", "rom-vault"))]);
        let tmp = tempfile::tempdir().unwrap();
        let config_content = r#"token = "${vault:slack.token}""#;
        std::fs::write(tmp.path().join("config.toml"), config_content).unwrap();

        let config = load_skill_config_with_vault(tmp.path(), Some(&vault))
            .unwrap()
            .unwrap();
        assert_eq!(
            config.table["token"].as_str().unwrap(),
            concat!("xoxb-f", "rom-vault")
        );
    }

    #[test]
    fn load_skill_config_vault_and_env_mixed() {
        let vault = MockVault::new(&[("slack.token", "from-vault")]);
        std::env::set_var("TEST_VAULT_MIX_KEY", "from-env");
        let tmp = tempfile::tempdir().unwrap();
        let config_content =
            "vault_val = \"${vault:slack.token}\"\nenv_val = \"${TEST_VAULT_MIX_KEY}\"";
        std::fs::write(tmp.path().join("config.toml"), config_content).unwrap();

        let config = load_skill_config_with_vault(tmp.path(), Some(&vault))
            .unwrap()
            .unwrap();
        assert_eq!(config.table["vault_val"].as_str().unwrap(), "from-vault");
        assert_eq!(config.table["env_val"].as_str().unwrap(), "from-env");
        std::env::remove_var("TEST_VAULT_MIX_KEY");
    }
}
