//! Memory consolidation — compresses episodic memories into semantic knowledge.
//!
//! Implements the "sleeping on it" model: periodic review that distills
//! experiences into reusable knowledge.

use chrono::{DateTime, Duration, Utc};
use serde::{Deserialize, Serialize};

use crate::types::{Memory, MemoryFilter, MemoryId, MemoryLayer, Visibility};
use workforce_core::types::AgentId;

/// Consolidation trigger configuration.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ConsolidationConfig {
    /// How often to run time-based consolidation (hours).
    #[serde(default = "default_interval_hours")]
    pub interval_hours: u32,
    /// Access count threshold for usage-based promotion.
    #[serde(default = "default_access_threshold")]
    pub access_threshold: u32,
    /// Days without access before relevance decay.
    #[serde(default = "default_decay_days")]
    pub decay_days: u32,
    /// Max episodic memories before capacity-based consolidation.
    #[serde(default = "default_capacity_limit")]
    pub capacity_limit: usize,
    /// Minimum importance score to keep during capacity cleanup.
    #[serde(default = "default_min_importance")]
    pub min_importance: f32,
}

impl Default for ConsolidationConfig {
    fn default() -> Self {
        Self {
            interval_hours: default_interval_hours(),
            access_threshold: default_access_threshold(),
            decay_days: default_decay_days(),
            capacity_limit: default_capacity_limit(),
            min_importance: default_min_importance(),
        }
    }
}

fn default_interval_hours() -> u32 {
    24
}
fn default_access_threshold() -> u32 {
    3
}
fn default_decay_days() -> u32 {
    90
}
fn default_capacity_limit() -> usize {
    10_000
}
fn default_min_importance() -> f32 {
    0.2
}

/// A consolidation job — tracks what memories need processing.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ConsolidationJob {
    pub id: String,
    pub agent_id: AgentId,
    pub trigger: ConsolidationTrigger,
    pub status: ConsolidationStatus,
    pub memories_processed: usize,
    pub memories_created: usize,
    pub memories_archived: usize,
    pub started_at: DateTime<Utc>,
    pub completed_at: Option<DateTime<Utc>>,
}

/// What triggered the consolidation.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ConsolidationTrigger {
    /// Scheduled time-based consolidation.
    Scheduled,
    /// Memory accessed frequently enough to promote.
    UsageBased,
    /// Episodic memory count exceeded capacity.
    CapacityPressure,
    /// Manually triggered by human or agent.
    Manual,
}

/// Status of a consolidation job.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ConsolidationStatus {
    Pending,
    Running,
    Completed,
    Failed,
}

/// A candidate memory cluster for consolidation.
#[derive(Debug, Clone)]
pub struct MemoryCluster {
    /// Source episodic memories in this cluster.
    pub source_memories: Vec<Memory>,
    /// Common topic/theme.
    pub topic: String,
    /// Consolidated summary (generated by LLM or simple merge).
    pub summary: String,
    /// Combined importance score.
    pub importance: f32,
}

/// The consolidation engine.
pub struct ConsolidationEngine {
    config: ConsolidationConfig,
}

impl ConsolidationEngine {
    pub fn new(config: ConsolidationConfig) -> Self {
        Self { config }
    }

    /// Check if time-based consolidation is due.
    pub fn is_due(&self, last_run: Option<DateTime<Utc>>) -> bool {
        match last_run {
            None => true,
            Some(last) => {
                let elapsed = Utc::now() - last;
                elapsed > Duration::hours(self.config.interval_hours as i64)
            }
        }
    }

    /// Identify memories that should be promoted from episodic to semantic
    /// based on access patterns.
    pub fn find_promotion_candidates<'a>(&self, memories: &'a [Memory]) -> Vec<&'a Memory> {
        memories
            .iter()
            .filter(|m| {
                m.layer == MemoryLayer::Episodic
                    && m.access_count >= self.config.access_threshold
                    && !m.deleted
            })
            .collect()
    }

    /// Identify memories that should have their relevance decayed.
    pub fn find_decay_candidates<'a>(&self, memories: &'a [Memory]) -> Vec<&'a Memory> {
        let cutoff = Utc::now() - Duration::days(self.config.decay_days as i64);
        memories
            .iter()
            .filter(|m| {
                m.layer == MemoryLayer::Semantic
                    && m.last_accessed < cutoff
                    && !m.deleted
                    && m.importance > self.config.min_importance
            })
            .collect()
    }

    /// Check if capacity-based consolidation is needed.
    pub fn needs_capacity_cleanup(&self, episodic_count: usize) -> bool {
        episodic_count > self.config.capacity_limit
    }

    /// Find low-importance episodic memories to archive during capacity cleanup.
    pub fn find_archive_candidates<'a>(&self, memories: &'a [Memory]) -> Vec<&'a Memory> {
        let mut candidates: Vec<&Memory> = memories
            .iter()
            .filter(|m| {
                m.layer == MemoryLayer::Episodic
                    && !m.deleted
                    && m.importance < self.config.min_importance
            })
            .collect();

        // Sort by importance (lowest first), then by date (oldest first)
        candidates.sort_by(|a, b| {
            a.importance
                .partial_cmp(&b.importance)
                .unwrap_or(std::cmp::Ordering::Equal)
                .then_with(|| a.created_at.cmp(&b.created_at))
        });

        candidates
    }

    /// Cluster related episodic memories by tags for consolidation.
    pub fn cluster_by_tags(&self, memories: &[Memory]) -> Vec<MemoryCluster> {
        use std::collections::HashMap;

        let mut tag_groups: HashMap<String, Vec<Memory>> = HashMap::new();

        for memory in memories {
            if memory.layer != MemoryLayer::Episodic || memory.deleted {
                continue;
            }
            for tag in &memory.tags {
                tag_groups
                    .entry(tag.clone())
                    .or_default()
                    .push(memory.clone());
            }
        }

        tag_groups
            .into_iter()
            .filter(|(_, mems)| mems.len() >= 2) // Only cluster groups with 2+ memories
            .map(|(topic, source_memories)| {
                let importance = source_memories.iter().map(|m| m.importance).sum::<f32>()
                    / source_memories.len() as f32;

                let summary = source_memories
                    .iter()
                    .map(|m| m.content.as_str())
                    .collect::<Vec<_>>()
                    .join(" | ");

                MemoryCluster {
                    source_memories,
                    topic,
                    summary,
                    importance,
                }
            })
            .collect()
    }

    /// Create a new semantic memory from a cluster of episodic memories.
    ///
    /// `identity_id` and `source_session_id` are each carried forward only when
    /// every attributed source memory shares the same value — otherwise they
    /// fall back to `None` so mixed clusters aren't silently misattributed.
    /// `source_message_ids` unions across all sources so drill-down still
    /// reaches the original turns.
    pub fn consolidate_cluster(&self, cluster: &MemoryCluster, owner: &AgentId) -> Memory {
        let identity_id = single_shared_value(
            cluster
                .source_memories
                .iter()
                .filter_map(|m| m.identity_id.as_deref()),
        );
        let source_session_id = single_shared_value(
            cluster
                .source_memories
                .iter()
                .filter_map(|m| m.source_session_id.as_deref()),
        );
        let source_message_ids = cluster
            .source_memories
            .iter()
            .flat_map(|m| m.source_message_ids.iter().cloned())
            .collect::<std::collections::BTreeSet<_>>()
            .into_iter()
            .collect();

        Memory {
            id: MemoryId::new(),
            content: cluster.summary.clone(),
            layer: MemoryLayer::Semantic,
            owner: owner.clone(),
            visibility: Visibility::Private,
            importance: cluster.importance.min(1.0),
            tags: vec![cluster.topic.clone(), "consolidated".to_string()],
            source: crate::types::MemorySource::Agent,
            identity_id,
            source_session_id,
            source_message_ids,
            created_at: Utc::now(),
            event_time: Utc::now(),
            last_accessed: Utc::now(),
            access_count: 0,
            recurrence_count: 0,
            last_recurrence_at: None,
            deleted: false,
        }
    }

    /// Calculate a decayed importance score.
    pub fn decay_importance(&self, current: f32, days_since_access: u64) -> f32 {
        let decay_factor = 0.95_f32.powi(days_since_access as i32 / 30);
        (current * decay_factor).max(self.config.min_importance)
    }
}

/// Return `Some(value)` when every non-empty item in the iterator is the same
/// value, else `None`. Used to propagate identity / session links through
/// consolidation only when the cluster is unambiguous.
fn single_shared_value<'a, I>(items: I) -> Option<String>
where
    I: IntoIterator<Item = &'a str>,
{
    let mut unique = items
        .into_iter()
        .collect::<std::collections::HashSet<_>>()
        .into_iter();
    match (unique.next(), unique.next()) {
        (Some(only), None) => Some(only.to_string()),
        _ => None,
    }
}

/// Filter for finding consolidation candidates. Caller is responsible for
/// passing `identity_id` for per-user consolidation; this helper opts into
/// `system_unscoped` because consolidation is a privileged background job
/// (per DW-518 — see `MemoryFilter::system_unscoped`).
pub fn episodic_filter(agent_id: &AgentId) -> MemoryFilter {
    MemoryFilter {
        owner: Some(agent_id.clone()),
        layer: Some(MemoryLayer::Episodic),
        limit: Some(10_000),
        ..MemoryFilter::system_unscoped()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn make_memory(
        content: &str,
        layer: MemoryLayer,
        importance: f32,
        access_count: u32,
        tags: Vec<&str>,
    ) -> Memory {
        let mut m = Memory::new(content, layer, AgentId::new("test-agent"))
            .with_importance(importance)
            .with_tags(tags.into_iter().map(String::from).collect());
        m.created_at = Utc::now() - Duration::hours(1);
        m.access_count = access_count;
        m
    }

    #[test]
    fn promotion_candidates() {
        let engine = ConsolidationEngine::new(ConsolidationConfig::default());
        let memories = vec![
            make_memory("used a lot", MemoryLayer::Episodic, 0.5, 5, vec!["rust"]),
            make_memory("used once", MemoryLayer::Episodic, 0.3, 1, vec!["rust"]),
            make_memory(
                "already semantic",
                MemoryLayer::Semantic,
                0.8,
                10,
                vec!["rust"],
            ),
        ];

        let candidates = engine.find_promotion_candidates(&memories);
        assert_eq!(candidates.len(), 1);
        assert_eq!(candidates[0].content, "used a lot");
    }

    #[test]
    fn decay_candidates() {
        let engine = ConsolidationEngine::new(ConsolidationConfig::default());
        let mut old_memory =
            make_memory("old knowledge", MemoryLayer::Semantic, 0.7, 5, vec!["old"]);
        old_memory.last_accessed = Utc::now() - Duration::days(100);

        let recent_memory = make_memory(
            "recent knowledge",
            MemoryLayer::Semantic,
            0.7,
            5,
            vec!["new"],
        );

        let memories = vec![old_memory, recent_memory];
        let candidates = engine.find_decay_candidates(&memories);
        assert_eq!(candidates.len(), 1);
        assert_eq!(candidates[0].content, "old knowledge");
    }

    #[test]
    fn capacity_check() {
        let engine = ConsolidationEngine::new(ConsolidationConfig {
            capacity_limit: 100,
            ..Default::default()
        });

        assert!(!engine.needs_capacity_cleanup(50));
        assert!(engine.needs_capacity_cleanup(150));
    }

    #[test]
    fn archive_candidates_sorted() {
        let engine = ConsolidationEngine::new(ConsolidationConfig::default());
        let memories = vec![
            make_memory("high importance", MemoryLayer::Episodic, 0.8, 1, vec![]),
            make_memory("low importance", MemoryLayer::Episodic, 0.1, 1, vec![]),
            make_memory("medium importance", MemoryLayer::Episodic, 0.15, 1, vec![]),
        ];

        let candidates = engine.find_archive_candidates(&memories);
        assert_eq!(candidates.len(), 2);
        assert_eq!(candidates[0].content, "low importance");
        assert_eq!(candidates[1].content, "medium importance");
    }

    #[test]
    fn cluster_by_tags_groups() {
        let engine = ConsolidationEngine::new(ConsolidationConfig::default());
        let memories = vec![
            make_memory(
                "rust deploy 1",
                MemoryLayer::Episodic,
                0.5,
                1,
                vec!["deploy"],
            ),
            make_memory(
                "rust deploy 2",
                MemoryLayer::Episodic,
                0.6,
                1,
                vec!["deploy"],
            ),
            make_memory("solo memory", MemoryLayer::Episodic, 0.3, 1, vec!["unique"]),
        ];

        let clusters = engine.cluster_by_tags(&memories);
        assert_eq!(clusters.len(), 1);
        assert_eq!(clusters[0].topic, "deploy");
        assert_eq!(clusters[0].source_memories.len(), 2);
    }

    #[test]
    fn consolidate_cluster_creates_semantic() {
        let engine = ConsolidationEngine::new(ConsolidationConfig::default());
        let cluster = MemoryCluster {
            source_memories: vec![],
            topic: "deployment".to_string(),
            summary: "Deployment always requires X then Y".to_string(),
            importance: 0.7,
        };

        let result = engine.consolidate_cluster(&cluster, &AgentId::new("agent"));
        assert_eq!(result.layer, MemoryLayer::Semantic);
        assert!(result.tags.contains(&"consolidated".to_string()));
        assert!(result.tags.contains(&"deployment".to_string()));
        assert_eq!(result.identity_id, None);
    }

    fn memory_with_identity(identity: Option<&str>) -> Memory {
        let mut m = make_memory("x", MemoryLayer::Episodic, 0.5, 1, vec!["t"]);
        m.identity_id = identity.map(String::from);
        m
    }

    fn cluster_from(sources: Vec<Memory>) -> MemoryCluster {
        MemoryCluster {
            source_memories: sources,
            topic: "t".to_string(),
            summary: "s".to_string(),
            importance: 0.5,
        }
    }

    #[test]
    fn consolidate_cluster_carries_identity_when_all_sources_match() {
        let engine = ConsolidationEngine::new(ConsolidationConfig::default());
        let cluster = cluster_from(vec![
            memory_with_identity(Some("user-a")),
            memory_with_identity(Some("user-a")),
        ]);
        let result = engine.consolidate_cluster(&cluster, &AgentId::new("agent"));
        assert_eq!(result.identity_id.as_deref(), Some("user-a"));
    }

    #[test]
    fn consolidate_cluster_drops_identity_on_mixed_sources() {
        let engine = ConsolidationEngine::new(ConsolidationConfig::default());
        let cluster = cluster_from(vec![
            memory_with_identity(Some("user-a")),
            memory_with_identity(Some("user-b")),
        ]);
        let result = engine.consolidate_cluster(&cluster, &AgentId::new("agent"));
        assert_eq!(result.identity_id, None);
    }

    #[test]
    fn consolidate_cluster_ignores_none_sources_when_a_single_identity_is_present() {
        let engine = ConsolidationEngine::new(ConsolidationConfig::default());
        let cluster = cluster_from(vec![
            memory_with_identity(Some("user-a")),
            memory_with_identity(None),
            memory_with_identity(None),
        ]);
        let result = engine.consolidate_cluster(&cluster, &AgentId::new("agent"));
        assert_eq!(result.identity_id.as_deref(), Some("user-a"));
    }

    #[test]
    fn consolidate_cluster_returns_none_identity_for_all_none_sources() {
        let engine = ConsolidationEngine::new(ConsolidationConfig::default());
        let cluster = cluster_from(vec![memory_with_identity(None), memory_with_identity(None)]);
        let result = engine.consolidate_cluster(&cluster, &AgentId::new("agent"));
        assert_eq!(result.identity_id, None);
    }

    fn memory_with_source(session: Option<&str>, messages: &[&str]) -> Memory {
        let mut m = make_memory("x", MemoryLayer::Episodic, 0.5, 1, vec!["t"]);
        m.source_session_id = session.map(String::from);
        m.source_message_ids = messages.iter().map(|s| s.to_string()).collect();
        m
    }

    #[test]
    fn consolidate_cluster_keeps_session_when_all_sources_agree() {
        let engine = ConsolidationEngine::new(ConsolidationConfig::default());
        let cluster = cluster_from(vec![
            memory_with_source(Some("sess-a"), &["m-1"]),
            memory_with_source(Some("sess-a"), &["m-2"]),
        ]);
        let result = engine.consolidate_cluster(&cluster, &AgentId::new("agent"));
        assert_eq!(result.source_session_id.as_deref(), Some("sess-a"));
        assert_eq!(result.source_message_ids, vec!["m-1", "m-2"]);
    }

    #[test]
    fn consolidate_cluster_drops_session_but_unions_messages_across_sessions() {
        let engine = ConsolidationEngine::new(ConsolidationConfig::default());
        let cluster = cluster_from(vec![
            memory_with_source(Some("sess-a"), &["m-1"]),
            memory_with_source(Some("sess-b"), &["m-9"]),
        ]);
        let result = engine.consolidate_cluster(&cluster, &AgentId::new("agent"));
        assert!(result.source_session_id.is_none());
        assert_eq!(result.source_message_ids, vec!["m-1", "m-9"]);
    }

    #[test]
    fn consolidate_cluster_handles_partial_source_metadata() {
        let engine = ConsolidationEngine::new(ConsolidationConfig::default());
        let cluster = cluster_from(vec![
            memory_with_source(Some("sess-a"), &["m-1"]),
            memory_with_source(None, &[]),
        ]);
        let result = engine.consolidate_cluster(&cluster, &AgentId::new("agent"));
        assert_eq!(result.source_session_id.as_deref(), Some("sess-a"));
        assert_eq!(result.source_message_ids, vec!["m-1"]);
    }

    #[test]
    fn importance_decay() {
        let engine = ConsolidationEngine::new(ConsolidationConfig::default());
        let decayed = engine.decay_importance(1.0, 90);
        assert!(decayed < 1.0);
        assert!(decayed > 0.0);

        // Very old memories still have minimum importance
        let very_decayed = engine.decay_importance(0.3, 365);
        assert!(very_decayed >= engine.config.min_importance);
    }

    #[test]
    fn is_due_check() {
        let engine = ConsolidationEngine::new(ConsolidationConfig::default());

        // Never run → always due
        assert!(engine.is_due(None));

        // Ran recently → not due
        assert!(!engine.is_due(Some(Utc::now())));

        // Ran long ago → due
        assert!(engine.is_due(Some(Utc::now() - Duration::hours(48))));
    }
}
